from fastapi import FastAPI
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel
import numpy as np
import tensorflow as tf
import joblib

app = FastAPI()

# Izinkan CORS agar Vercel dapat mengakses API ini
app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)

# Definisikan fungsi kustom root_mean_squared_error dengan decorator yang kompatibel
@tf.keras.utils.register_keras_serializable()
def root_mean_squared_error(y_true, y_pred):
    return tf.math.sqrt(tf.math.reduce_mean(tf.math.square(y_pred - y_true)))

# Load Model & Scaler saat startup dengan menyertakan custom_objects jika diperlukan
try:
    model = tf.keras.models.load_model(
        "model_lstm.keras",
        custom_objects={"root_mean_squared_error": root_mean_squared_error}
    )
except Exception as e:
    # Beberapa versi Keras mendeserialisasi dengan nama fungsi kustom secara langsung
    model = tf.keras.models.load_model("model_lstm.keras", compile=False)
    model.compile(optimizer="adam", loss=root_mean_squared_error)

scaler = joblib.load("scaler.joblib")

class PredictRequest(BaseModel):
    # Urutan 30 hari terakhir, masing-masing mengandung [postcode, price, propertyType, bedrooms]
    sequence: list[list[float]]

@app.get("/")
def home():
    return {"status": "API Prediksi Harga Properti Aktif"}

@app.post("/predict")
def predict(data: PredictRequest):
    # Ubah input menjadi numpy array (shape: 1, 30, 4)
    input_array = np.array(data.sequence)
    if input_array.shape != (30, 4):
        return {"error": "Format data harus berupa 30 langkah waktu x 4 fitur"}

    # Scale data input
    input_scaled = scaler.transform(input_array)
    input_scaled = np.expand_dims(input_scaled, axis=0)

    # Prediksi menggunakan model LSTM
    pred_scaled = model.predict(input_scaled)[0, 0]

    # Inverse transform untuk mendapatkan harga aktual
    dummy = np.zeros((1, 4))
    dummy[0, 1] = pred_scaled  # Kolom harga berada pada indeks 1
    pred_actual = scaler.inverse_transform(dummy)[0, 1]

    return {"predicted_price": float(pred_actual)}